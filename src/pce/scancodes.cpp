GenScanCode R2KeyCodeToGenScanCode(u32 key_code)
{
  const auto iter = std::lower_bound(std::begin(s_r2_scancode_mapping), std::end(s_r2_scancode_mapping), key_code,
                                     [](const auto& it, const auto& value) { return (it.first < value); });
  return (iter != std::end(s_r2_scancode_mapping) && iter->first == key_code) ? iter->second : GenScanCode_None;
}
